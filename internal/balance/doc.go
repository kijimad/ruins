// Package balance はゲームバランスを実際にプレイせず定量評価する。閉形式の期待値導出と
// モンテカルロシミュレーションの2系統を持つ。
//
// # 目的
//
// パラメータ変更がゲーム体験に与える影響を、実際にプレイせずに定量的に評価する。
// 深度ごとのHP推移・突然死率・武器遷移を統計的に可視化し、
// 難易度曲線の妥当性を検証する。
//
// # 導出系とシミュレーション系
//
// 2つの評価系がある。用途で使い分ける。
//
// ドメインごとにどのアプローチとメトリクスを採用するかは docs/balance/approach.md に定める。
// 新しい指標を足すときは、まずそこで層とコード出典を確認する。式の再実装を避けるため。
//
//   - 導出系: metrics.go・markov.go・survival.go・logistics.go・economy.go とドメイン別ファイル群、
//     集約は baseline.go。実コードの戦闘式や消費式から期待値と分布を閉形式で計算し、dangerLevel(day)
//     から日ごとの難易度カーブを乱数なしで引く。決定論的でミリ秒で完了し、目標回廊との照合に使う。
//     閉形式が実式と一致することは markov_test.go でモンテカルロと突き合わせて担保する。
//   - シミュレーション系: combat.go と run.go。分布の裾すなわち不運の連鎖を見る用途に残す。
//
// # アーキテクチャ
//
// ゲーム本体の戦闘ロジック（activity/attack.go）はECS依存のため、
// シミュレーション用にECS非依存の純粋関数として計算式を再実装している。
// 計算式の定数と基本関数は formula パッケージに集約し、両者で共有している。
//
// # シミュレーションの階層
//
// 3段階の粒度でシミュレーションを提供する。
//
//   - 戦闘レベル: SimulateBattle は1対1の戦闘を模擬する。
//     プレイヤーと敵が交互に攻撃し、どちらかのHPが0以下になるまで繰り返す。
//     命中判定・ダメージ計算・クリティカルヒットを含む。
//
//   - フロアレベル: SimulateRun の各深度ループが1フロアに対応する。
//     フロアごとに 3+rand(3) 体の敵と連続戦闘し、
//     フロア終了後にアイテムテーブルから回復アイテムと武器を取得する。
//     より強い武器を拾った場合、以降の戦闘でその武器を使用する。
//
//   - ランレベル: RunSimulations はN回のランを実行し、RunStats に集約する。
//     各ランは独立したシード値を持ち、再現可能である。
//
// # 戦闘計算式
//
// 計算式の詳細は formula パッケージを参照すること。
// 主要な計算式の概要を以下に示す。
//
// # フロアのアイテム取得
//
// 各フロア終了時に、対応するアイテムテーブルから 15+rand(9) 個のアイテムを抽選する。
// 回復アイテムはHPに加算し、武器アイテムはフロア内で最も強いものを選択する。
// 現在の武器よりダメージが高い場合のみ切り替える。
// この数値は mapplanner のアイテム配置ロジックと一致させている。
//
// # 統計指標
//
//   - 到達深度中央値: N回のランで到達した深度の中央値
//   - 突然死率: ある深度に到達したランのうち、その深度で死亡した割合。
//     敵の強さの急変を検出するのに有用である
//   - HP P5/P95: 残HPの下位5%・上位95%パーセンタイル。
//     最悪ケースと最良ケースの幅を示す
//   - 武器分布: 各深度で使用されている武器の割合。
//     装備成長の進行度を確認できる
//
// # 既知の制約
//
//   - 属性相性・状態異常は未実装であり、実プレイとの乖離要因になる。スキルは進行カーブが想定値として織り込む
//   - 敵の行動は最も重みの高い攻撃のみを使用する簡略化モデルである
//   - 防具の装備成長は未対応である
//   - 戦闘の行動順はプレイヤー先攻固定である
//
// # パラメータベクトル
//
// バランスに効くつまみは params.go の Params に1つのベクトルとして集約する。導出関数は
// Params の純関数として書き、ゲーム定数との接点は DefaultParams だけに限る。感度・交換
// レート・探索は knobRegistry の成分を摂動する汎用機械として実装し、つまみの追加は
// Params の成分とレジストリの1行で済む。
//
// # ファイル構成
//
//   - params.go: パラメータベクトル Params と、ゲーム定数から初期化する DefaultParams
//   - metrics.go: 期待ダメージ・実効撃破打数・難易度カーブの閉形式導出
//   - markov.go: 戦闘を吸収マルコフ連鎖として厳密に解き、死亡確率とTTK分布を導く。期待値の裾側
//   - progression.go: 想定攻撃頻度から各日の想定スキルを導き、静的下限と想定プレイヤーの進行カーブを並べる
//   - climate.go: 世界温度の季節変動を閉形式で導出。生存の寒さ圧の上流入力
//   - survival.go: 飢え・寒さ・血液→HP・疲労・睡眠回復の生存圧を閉形式で導出
//   - logistics.go: 燃料・重量・航続と燃焼ターンの物流指標を閉形式で導出
//   - economy.go: 競売の手取り率・1個あたりの期待手取り・探索1回の期待収入(層数入力)を閉形式で導出。到達層数の分布と移動コスト側はC/設計値
//   - growth.go: スキル成長を実物 skill.GainExp の反復で導出。Lv到達までの攻撃回数
//   - build.go: 想定攻撃回数から導くスキル熟練度で代表ビルドを作り、戦力比の振れ幅を段階別に評価する
//   - search.go: 単変数の目標探索・多目的Pareto探索
//   - sensitivity.go: つまみレジストリと、つまみ×メトリクスのドメイン横断感度行列(ヤコビアン)
//   - exchange.go: 同じメトリクスを保つためのつまみ間の相互補償を実式の二分探索で解く交換レート
//   - boundary.go: つまみを動かして目標帯を割るまでの余白を解く境界マージン。凍結ゲートの余白監視版
//   - restriction.go: 武器を素手へ制限したときの死亡確率の劣化量。要素の必須度を測る Restricted Play 系
//   - skilldepth.go: スキル進行の手応え。丸めで死んだティアと実効ティアを分ける NTBEA 系のティア識別性
//   - viability.go: 武器ロスターの viability 要約。使える武器の割合と symmetry 判定。Pfau のプレイヤー選好系
//   - targets.go: ドメイン横断のスカラー指標と目標帯の照合
//   - baseline.go: 目標帯との照合とベースライン markdown 生成
//   - combat.go: 戦闘計算式とデータロード
//   - run.go: フロア・ランのシミュレーション実行
//   - stats.go: 統計集計とパーセンタイル計算
package balance
