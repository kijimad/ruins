// Package raidmap は襲撃の敵が下る、狙う的から現ステージの各マスへの重み付きの距離の地図を作る。
//
// # 責務
//
// 空間の索引と置物から、各マスへ入る重みを書き出し、的から距離を広げる。敵は手番ごとに、自分の隣で距離の
// 一番小さいマスへ進む。群れの全員が同じ1枚の地図を下るので、敵ごとに道を探さずに済む。
//
// # 使い分け
//
// 波を湧かせる internal/systems は、的まで道のつながるマスを選ぶのに使う。敵の手番を決める internal/aiinput は、
// 印のある敵の次の1歩を選ぶのに使う。1体の敵が1つの的へ向かう道探しは activity.FindNextStep を使う。
//
// # 仕様
//
// 重みの決め方と斜めの規則は Build の doc に書く。距離の配列は作る側が持って使い回す。
