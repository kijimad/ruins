// Command gen は rawschema の CUE の定義から Go の型を生成する。
//
// CUE のファイルを構文として読み、限られた書き方だけを Go へ写す。想定外の書き方はエラーで止め、黙って
// 読み飛ばさない。写し方は次のとおり。
//
//   - 構造体の定義は構造体にする。フィールドは Go の名前の順に並べる。省略できるフィールドはポインタにする
//   - 文字列の選択肢は名前付きの型にし、値ごとの定数と Valid と、値をスキーマに書いた順に返す XxxValues を足す
//   - 制約付きのスカラーは別名にする
//   - 空の構造体は map[string]interface{} の別名にする
//   - [...T] は []T にする
//
// 属性 @rawgen で写し方を変える。type=X は Go の型を X にする。prefix は定数の名前の前に型の名前を付ける。
// - はそのフィールドを Go に写さない。参照の検査のためだけのフィールドに使う。構造体の中の内包表記は、
// 中身が - のフィールドだけなら Go に写さずに許す。省略できるフィールドがあるときだけ検査するのに使う。
package main

import (
	"bytes"
	"errors"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
	"unicode"

	"cuelang.org/go/cue/ast"
	"cuelang.org/go/cue/parser"
	"cuelang.org/go/cue/token"
)

const (
	outputFile = "models_gen.go"
	goInt      = "int"
	goFloat64  = "float64"
)

var errUnsupported = errors.New("unsupported CUE expression")

func main() {
	if err := run("."); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func run(dir string) error {
	paths, err := filepath.Glob(filepath.Join(dir, "*.cue"))
	if err != nil {
		return err
	}
	sort.Strings(paths)
	var decls []*ast.Field
	for _, p := range paths {
		f, err := parser.ParseFile(p, nil, parser.ParseComments)
		if err != nil {
			return err
		}
		for _, d := range f.Decls {
			fd, ok := d.(*ast.Field)
			if !ok {
				continue
			}
			if name, ok := labelName(fd.Label); ok && strings.HasPrefix(name, "#") {
				decls = append(decls, fd)
			}
		}
	}
	src, err := generate(decls)
	if err != nil {
		return err
	}
	return os.WriteFile(filepath.Join(dir, outputFile), src, 0o644)
}

// generate は定義の並びから Go のソースを組み、gofmt で整えて返す。
func generate(decls []*ast.Field) ([]byte, error) {
	sort.Slice(decls, func(i, j int) bool {
		a, _ := labelName(decls[i].Label)
		b, _ := labelName(decls[j].Label)
		return a < b
	})
	var b bytes.Buffer
	b.WriteString("// Code generated by internal/rawschema/gen. DO NOT EDIT.\n\npackage rawschema\n")
	for _, d := range decls {
		if err := writeDecl(&b, d); err != nil {
			return nil, err
		}
	}
	out, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("gofmt: %w\n%s", err, b.String())
	}
	return out, nil
}

func writeDecl(b *bytes.Buffer, d *ast.Field) error {
	label, _ := labelName(d.Label)
	name := strings.TrimPrefix(label, "#")
	attrs := rawgenAttrs(d)
	writeDoc(b, name, d)
	if t, ok := attrs["type"]; ok {
		fmt.Fprintf(b, "type %s = %s\n\n", name, t)
		return nil
	}
	switch v := d.Value.(type) {
	case *ast.StructLit:
		return writeStruct(b, name, v)
	case *ast.ListLit:
		elem, err := listElem(v)
		if err != nil {
			return fmt.Errorf("%s: %w", name, err)
		}
		fmt.Fprintf(b, "type %s = []%s\n\n", name, elem)
		return nil
	}
	if values, ok := stringEnum(d.Value); ok {
		_, prefix := attrs["prefix"]
		writeEnum(b, name, "string", quoted(values), values, prefix)
		writeValues(b, name, values, prefix)
		return nil
	}
	if values, ok := numberEnum(d.Value); ok {
		under := attrs["enum"]
		if under == "" {
			under = goInt
		}
		writeEnum(b, name, under, values, values, false)
		return nil
	}
	t, err := goType(d.Value)
	if err != nil {
		return fmt.Errorf("%s: %w", name, err)
	}
	fmt.Fprintf(b, "type %s = %s\n\n", name, t)
	return nil
}

type goField struct {
	name, typ, tag, doc string
}

func writeStruct(b *bytes.Buffer, name string, s *ast.StructLit) error {
	var fields []goField
	for _, e := range s.Elts {
		if c, ok := e.(*ast.Comprehension); ok {
			if err := checkOnlyComprehension(c); err != nil {
				return fmt.Errorf("%s: %w", name, err)
			}
			continue
		}
		f, ok := e.(*ast.Field)
		if !ok {
			return fmt.Errorf("%s: %w: %T", name, errUnsupported, e)
		}
		label, ok := labelName(f.Label)
		if !ok {
			return fmt.Errorf("%s: %w: label %T", name, errUnsupported, f.Label)
		}
		attrs := rawgenAttrs(f)
		if _, skip := attrs["-"]; skip {
			continue
		}
		t, ok := attrs["type"]
		if !ok {
			var err error
			t, err = goType(f.Value)
			if err != nil {
				return fmt.Errorf("%s.%s: %w", name, label, err)
			}
		}
		tag := label
		if f.Constraint == token.OPTION {
			t = "*" + t
			tag += ",omitempty"
		}
		fields = append(fields, goField{name: fieldName(label), typ: t, tag: tag, doc: docText(f)})
	}
	if len(fields) == 0 {
		fmt.Fprintf(b, "type %s = map[string]interface{}\n\n", name)
		return nil
	}
	sort.Slice(fields, func(i, j int) bool { return fields[i].name < fields[j].name })
	fmt.Fprintf(b, "type %s struct {\n", name)
	for _, f := range fields {
		if f.doc != "" {
			fmt.Fprintf(b, "%s\n", commentLines(f.name+" "+f.doc, "\t"))
		}
		fmt.Fprintf(b, "\t%s %s `json:%q`\n\n", f.name, f.typ, f.tag)
	}
	b.WriteString("}\n\n")
	return nil
}

// checkOnlyComprehension は内包表記が @rawgen(-) のフィールドだけを持つことを確かめる。
// 内包表記はあるかないかが値で決まり Go のフィールドに写せないので、検査のためだけに許す。
func checkOnlyComprehension(c *ast.Comprehension) error {
	s, ok := c.Value.(*ast.StructLit)
	if !ok {
		return fmt.Errorf("%w: comprehension value %T", errUnsupported, c.Value)
	}
	for _, e := range s.Elts {
		f, ok := e.(*ast.Field)
		if !ok {
			return fmt.Errorf("%w: comprehension element %T", errUnsupported, e)
		}
		if _, skip := rawgenAttrs(f)["-"]; !skip {
			label, _ := labelName(f.Label)
			return fmt.Errorf("%w: comprehension field %s without @rawgen(-)", errUnsupported, label)
		}
	}
	return nil
}

// writeEnum は enum の型と定数と Valid を書く。literals は定数の値の Go の書き方、names は定数の名前の元にする値。
func writeEnum(b *bytes.Buffer, name, under string, literals, values []string, prefix bool) {
	fmt.Fprintf(b, "type %s %s\n\n", name, under)
	consts := make([]string, len(values))
	for i, v := range values {
		c := constName(v)
		if prefix {
			c = name + c
		}
		consts[i] = c
	}
	order := make([]int, len(values))
	for i := range order {
		order[i] = i
	}
	sort.Slice(order, func(i, j int) bool { return consts[order[i]] < consts[order[j]] })
	fmt.Fprintf(b, "// Defines values for %s.\nconst (\n", name)
	for _, i := range order {
		fmt.Fprintf(b, "\t%s %s = %s\n", consts[i], name, literals[i])
	}
	b.WriteString(")\n\n")
	fmt.Fprintf(b, "// Valid indicates whether the value is a known member of the %s enum.\nfunc (e %s) Valid() bool {\n\tswitch e {\n", name, name)
	for _, i := range order {
		fmt.Fprintf(b, "\tcase %s:\n\t\treturn true\n", consts[i])
	}
	b.WriteString("\tdefault:\n\t\treturn false\n\t}\n}\n\n")
}

// writeValues は文字列の enum の値を、CUE に書いた順に返す関数を書く。
func writeValues(b *bytes.Buffer, name string, values []string, prefix bool) {
	fmt.Fprintf(b, "// %sValues は %s の値を、スキーマに書いた順に返す。\nfunc %sValues() []%s {\n\treturn []%s{", name, name, name, name, name)
	for i, v := range values {
		if i > 0 {
			b.WriteString(", ")
		}
		c := constName(v)
		if prefix {
			c = name + c
		}
		b.WriteString(c)
	}
	b.WriteString("}\n}\n\n")
}

// goType は値の式から Go の型を決める。定義の参照はその名前、基本の型は Go の型、[...T] はスライスにする。
func goType(e ast.Expr) (string, error) {
	switch v := e.(type) {
	case *ast.Ident:
		if after, ok := strings.CutPrefix(v.Name, "#"); ok {
			return after, nil
		}
		if t, ok := basicTypes[v.Name]; ok {
			return t, nil
		}
	case *ast.ListLit:
		elem, err := listElem(v)
		if err != nil {
			return "", err
		}
		return "[]" + elem, nil
	case *ast.BinaryExpr:
		if v.Op == token.AND {
			return andType(v)
		}
	case *ast.ParenExpr:
		return goType(v.X)
	}
	return "", fmt.Errorf("%w: %T", errUnsupported, e)
}

// andType は a & b の Go の型を返す。片方が型で他方が制約なら型の側を使い、両方が型で食い違えば扱えない。
func andType(v *ast.BinaryExpr) (string, error) {
	x, errX := goType(v.X)
	y, errY := goType(v.Y)
	switch {
	case errX == nil && errY == nil && x != y:
		return "", fmt.Errorf("%w: conflicting types %s & %s", errUnsupported, x, y)
	case errX == nil:
		return x, nil
	default:
		return y, errY
	}
}

var basicTypes = map[string]string{
	"int":     goInt,
	"int32":   "int32",
	"int64":   "int64",
	"uint8":   "uint8",
	"float":   goFloat64,
	"float32": "float32",
	"float64": goFloat64,
	"number":  goFloat64,
	"string":  "string",
	"bool":    "bool",
}

func listElem(l *ast.ListLit) (string, error) {
	if len(l.Elts) != 1 {
		return "", fmt.Errorf("%w: list with %d elements", errUnsupported, len(l.Elts))
	}
	el, ok := l.Elts[0].(*ast.Ellipsis)
	if !ok || el.Type == nil {
		return "", fmt.Errorf("%w: list without ellipsis type", errUnsupported)
	}
	return goType(el.Type)
}

func quoted(values []string) []string {
	out := make([]string, len(values))
	for i, v := range values {
		out[i] = strconv.Quote(v)
	}
	return out
}

// numberEnum は式が整数の選択肢なら、その値を書いた順に返す。
func numberEnum(e ast.Expr) ([]string, bool) {
	switch v := e.(type) {
	case *ast.BasicLit:
		if v.Kind != token.INT {
			return nil, false
		}
		return []string{v.Value}, true
	case *ast.BinaryExpr:
		if v.Op != token.OR {
			return nil, false
		}
		x, ok := numberEnum(v.X)
		if !ok {
			return nil, false
		}
		y, ok := numberEnum(v.Y)
		if !ok {
			return nil, false
		}
		return append(x, y...), true
	}
	return nil, false
}

// stringEnum は式が文字列の選択肢なら、その値を書いた順に返す。
func stringEnum(e ast.Expr) ([]string, bool) {
	switch v := e.(type) {
	case *ast.BasicLit:
		if v.Kind != token.STRING {
			return nil, false
		}
		s, err := strconv.Unquote(v.Value)
		if err != nil {
			return nil, false
		}
		return []string{s}, true
	case *ast.BinaryExpr:
		if v.Op != token.OR {
			return nil, false
		}
		x, ok := stringEnum(v.X)
		if !ok {
			return nil, false
		}
		y, ok := stringEnum(v.Y)
		if !ok {
			return nil, false
		}
		return append(x, y...), true
	}
	return nil, false
}

func labelName(l ast.Label) (string, bool) {
	switch v := l.(type) {
	case *ast.Ident:
		return v.Name, true
	case *ast.BasicLit:
		s, err := strconv.Unquote(v.Value)
		return s, err == nil
	}
	return "", false
}

// rawgenAttrs は @rawgen の属性を、キーと値の組で返す。値の無いキーは空文字にする。
func rawgenAttrs(f *ast.Field) map[string]string {
	out := map[string]string{}
	for _, a := range f.Attrs {
		key, body := a.Split()
		if key != "rawgen" {
			continue
		}
		for part := range strings.SplitSeq(body, ",") {
			part = strings.TrimSpace(part)
			if part == "" {
				continue
			}
			k, v, _ := strings.Cut(part, "=")
			out[k] = v
		}
	}
	return out
}

// fieldName は JSON のキーから Go のフィールド名を作る。先頭を大文字にし、_ と - の区切りをつなぐ。
func fieldName(label string) string {
	return camel(label)
}

// constName は enum の値から定数の名前を作る。数字で始まる値は N を前に付ける。
func constName(v string) string {
	c := camel(v)
	if c != "" && unicode.IsDigit(rune(c[0])) {
		c = "N" + c
	}
	return c
}

func camel(s string) string {
	parts := strings.FieldsFunc(s, func(r rune) bool { return r == '_' || r == '-' || r == ' ' || r == '.' })
	var b strings.Builder
	for _, p := range parts {
		r := []rune(p)
		r[0] = unicode.ToUpper(r[0])
		b.WriteString(string(r))
	}
	return b.String()
}

func writeDoc(b *bytes.Buffer, name string, f *ast.Field) {
	if doc := docText(f); doc != "" {
		fmt.Fprintf(b, "%s\n", commentLines(name+" "+doc, ""))
	}
}

func docText(f *ast.Field) string {
	var lines []string
	for _, cg := range ast.Comments(f) {
		if !cg.Doc {
			continue
		}
		for _, c := range cg.List {
			lines = append(lines, strings.TrimSpace(strings.TrimPrefix(c.Text, "//")))
		}
	}
	return strings.Join(lines, "\n")
}

func commentLines(text, indent string) string {
	var out []string
	for l := range strings.SplitSeq(text, "\n") {
		out = append(out, indent+"// "+l)
	}
	return strings.Join(out, "\n")
}
