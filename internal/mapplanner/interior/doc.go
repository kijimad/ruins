// Package interior は施設内装の content システムを担う。
//
// # 責務
//
// 建物という有界インスタンスの内側に、家具・戦利品・敵・装飾を「意味のある位置」へ置く。
// ランダム散布をやめ「設計されたもの」に見せることが目的。docs/design/20260725_70.md の翻案。
//
// content は「どの prefab か」でなく「どういう部屋が要るか」を要件で宣言し、要件を満たす任意の
// 部屋へ流し込む。幾何(部屋の形)と中身(何を置くか)を分離するのが器の芯。
//
// # 段階
//
// 本パッケージは doc 70 の段階導入に沿って育てる。現状で以下まで実装した。
//   - 抽選: Content が Group の列を持ち、Style で「必ず全部(PickEach)・重みで1つ(PickOne)・N個(PickN)」
//     を選ぶ。これが「店を店たらしめる物を必ず置き、風味だけを抽選する」散布殺しの芯。
//   - 配置(placement): 中央・壁際・奥・入口近く・列、といった密度場で座標を与える。到達性ガードで
//     戸口から全床へ届くことを保証する。
//   - 束(Satellites): 抽選の単位を単品でなく anchor 付きの束にする。机を anchor に椅子を相対配置し、
//     机だけあって椅子が無い・椅子が散らばる事故を構造で防ぐ。doc の効き目ランク Stage 2 の主装置。
//   - Archetype(archetypeOf): 家具型が自分の既定配置を知る。レシピは Ref と個数だけ言えばよく、置き方は
//     archetype が補う。同じ家具型は施設をまたいでも同じ置き方に揃い、レシピ間の重複と食い違いを防ぐ。
//   - 時間の層(Age): 略奪・生活痕・廃墟化を順に掛け、打ち捨てられた見た目にする。
//   - 分割文法(SplitBuilding): footprint を BSP で複数部屋へ割り、全域木で戸口連結し、建物入口を開ける。
//     部屋ごとに FillRoom を流すことで、1棟の施設を生成できる。役割は入口からの距離で分けるゾーン分類。
//   - 廊下型間取り(PlanHouse / PlanHouseVertical): 玄関から廊下、廊下から各室、という動線を持つ民家を
//     作る。均一な部屋の BSP では作れない狭い玄関・廊下・水回りの小部屋を、役割付きのテンプレートで
//     保証する。小部屋は「入れ子分割＋兄弟経由アクセス」で作るので、横廊下でも縦廊下でも成り立つ。
//   - 検証(classifyRoom): 配置から役割を逆推定する QA。生成が役割から家具を置くのに対し、家具から役割を
//     読み、店のはずが店に見えない生成失敗を機械検出する。多 seed で回して golden の目視前に退行を止める。
//
// RoomReq 照合による施設種の抽選、entrance からの BFS 距離によるゾーン分類は後続 Stage で足す。
//
// # 決定性
//
// 内装は再訪で一致し serde 安全であること。すべての抽選を有界インスタンスの seed 固定に閉じる。
//   - 抽選は slice に集め安定 sort してから seed で引く。Go の map を抽選に使わない
//   - seed は childSeed(parentSeed, index) の引数導出で分岐する。可変な乱数器の持ち回りをしない
//   - 同 seed 2回生成の完全一致をテストで強制する
