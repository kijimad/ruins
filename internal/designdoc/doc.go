// Package designdoc は docs/design 下の設計ドキュメントの frontmatter を扱う。
//
// # 責務
//   - 設計ドキュメント冒頭の YAML frontmatter の解析と検証
//   - 進捗チェックボックスからの status の決定的な導出
//   - frontmatter を欠くドキュメントへの決定的な付与と補完
//
// # 仕様
//   - frontmatter は status・tags・auto の3フィールドを持つ。status は Issue の open/closed に相当し、
//     auto はルーチンが無人で着手してよいかを表す。
//   - status の導出は `## 進捗` のチェックボックスだけを根拠にする。LLM 推論を挟まないため、
//     同じ入力に対して常に同じ結果を返す。
//
// # 進捗チェックボックスの対応フォーマット
//
// `## 進捗` セクション内の行頭チェックボックスだけを解釈する。対応する記法は次の3つに限る。
//   - `- [ ]` 未着手。open として数える。
//   - `- [x]` 完了。done として数える。
//   - `- [~]` 意図的に着手しない。不採用・見送り。open にも done にも数えず、進捗の分母から外す。
//
// これ以外の記法、たとえば `- [-]` や `- [/]` は解釈しない。表記を `- [~]` に統一する。
//
// # ステータスの遷移基準
//
// status は frontmatter に人が記す。遷移の基準を次に定める。前半はアクションが要る open な状態、
// 後半は閉じた状態で、Status.IsOpen がこの境目を返す。
//   - draft       下書き。方針がまだ固まっていない。新規ドキュメントの既定。
//   - accepted    方針は合意したが実装に着手していない。
//   - in-progress 実装に着手し、進捗に未完タスク `- [ ]` が残る。
//   - done        アクションが残っていない。進捗の open な `- [ ]` がゼロ、
//     または実装タスクを持たない意思決定ドキュメントで方向が確定した。
//   - superseded  後続ドキュメントに置き換えた。
//   - dropped     不採用として打ち切った。
//
// done の不変条件は Validate が守る。open な `- [ ]` が残る done は弾く。着手しないと決めたタスクは
// `- [~]` にすれば open から外れ、done にできる。進捗セクション自体を持たない意思決定ドキュメントは
// open がゼロなので、そのまま done にできる。
//
// # README に載せる範囲
//
// README の状況テーブルは IsOpen が true の status、すなわちアクションが要る draft・accepted・
// in-progress だけを一覧する。閉じた done・superseded・dropped は一覧しない。
// 「まだ何かする必要があるか」を IsOpen 一箇所で判定し、表示と分類の基準を一致させる。
//
// # 設計意図
//
// GitHub Issue を運用せず docs/design をバックログ兼 Issue トラッカーとして使うための土台。
// 構造は本パッケージが決定的に守り、意味付け、すなわち tags と auto の選択だけを人の判断に残す。
