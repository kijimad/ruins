package consts

// Mix64 は splitmix64 の仕上げで x を撹拌する
func Mix64(x uint64) uint64 {
	x ^= x >> 30
	x *= 0xBF58476D1CE4E5B9
	x ^= x >> 27
	x *= 0x94D049BB133111EB
	x ^= x >> 31
	return x
}

// Mix2D は seed と2次元の座標 (x, y) を撹拌した決定的な値を返す。チャンクごとの抽選の seed や、マスごとの見た目の
// ばらつきの源にする。
//
// x と y を別々の大きな奇数で混ぜてから Mix64 で撹拌する。狙いは2つ。
//   - 転置で散らす: x と y に別の定数を掛けるので (x,y) と (y,x) が別の値になる。同じ定数だと対称になり、転置した
//     座標が衝突して対角線状の反復が出る。
//   - 隣接で散らす: 撹拌の雪崩効果で (x,y) と (x+1,y) のような1違いの入力が無相関の値になる。撹拌しないと隣接の値が
//     定数差の線形関係になり、隣り合う場所が似てしまう。
//
// 奇数を掛けるのは 2^64 を法として可逆で座標の情報を落とさないため。定数を変えると同じ seed でも別の世界になる
func Mix2D[T ~int](seed uint64, x, y T) uint64 {
	return Mix64(seed + uint64(x)*0x9E3779B97F4A7C15 + uint64(y)*0xC2B2AE3D27D4EB4F)
}
